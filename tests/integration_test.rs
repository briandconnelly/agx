//! End-to-end integration tests for agx workflows.
//!
//! These tests exercise real workflows using the library API (not the binary).
//! No network access is required — all dependencies are local.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use tempfile::tempdir;

use agx::backends::{get_backend, ResolvedEnvironment};
use agx::context::generate_context_files;
use agx::lockfile;
use agx::lockfile::types::LockedSource;
use agx::manifest;
use agx::manifest::validate;
use agx::resolver::{resolve_all, ResolveContext};

/// Path to the full-local-project fixture directory.
fn fixture_dir() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/full-local-project")
}

/// Copy the full-local-project fixture into a tempdir for isolated testing.
fn setup_project(dir: &Path) {
    let src = fixture_dir();
    agx::backends::copy_dir_recursive(&src, dir).unwrap();
}

/// Build a ResolveContext for a manifest with only local dependencies.
/// Local deps don't need registry or git data, so the context is empty.
fn empty_resolve_context() -> ResolveContext {
    ResolveContext {
        registry_versions: BTreeMap::new(),
        git_commits: BTreeMap::new(),
    }
}

// ---------------------------------------------------------------------------
// Test 1: Full local workflow (the "golden path")
// ---------------------------------------------------------------------------

#[test]
fn test_full_local_workflow() {
    let tmp = tempdir().unwrap();
    let project_dir = tmp.path();
    setup_project(project_dir);

    // 1. Load manifest
    let manifest_path = project_dir.join("agent-environment.yml");
    let manifest = manifest::load(&manifest_path).unwrap();
    assert_eq!(manifest.name, "example-project");
    assert_eq!(manifest.backends.len(), 2);
    assert!(manifest.backends.contains_key("claude-code"));
    assert!(manifest.backends.contains_key("gemini-cli"));
    assert_eq!(manifest.skills.len(), 1);
    assert_eq!(manifest.agents.len(), 1);
    assert!(manifest.context.is_some());

    // 2. Validate manifest
    validate::validate(&manifest).unwrap();

    // 3. Resolve all dependencies to produce a lockfile
    let context = empty_resolve_context();
    let plugin_assets = BTreeMap::new();
    let lockfile = resolve_all(&manifest, &context, &plugin_assets).unwrap();

    // 4. Verify lockfile structure
    assert_eq!(lockfile.skills.len(), 1);
    assert!(lockfile.skills.contains_key("deploy-checklist"));
    match &lockfile.skills["deploy-checklist"].source {
        LockedSource::Local { local } => {
            assert_eq!(local, "./skills/deploy-checklist");
        }
        other => panic!("expected Local source for skill, got {:?}", other),
    }

    assert_eq!(lockfile.agents.len(), 1);
    assert!(lockfile.agents.contains_key("code-reviewer"));
    match &lockfile.agents["code-reviewer"].source {
        LockedSource::Local { local } => {
            assert_eq!(local, "./agents/code-reviewer.md");
        }
        other => panic!("expected Local source for agent, got {:?}", other),
    }

    // 5. Generate for each backend
    let cache_dir = tempdir().unwrap();
    let resolved = ResolvedEnvironment {
        manifest: &manifest,
        lockfile: &lockfile,
        cache_dir: cache_dir.path(),
    };

    // Claude Code backend
    let claude_backend = get_backend("claude-code").unwrap();
    claude_backend.generate(&resolved, project_dir).unwrap();

    // Verify .claude/ directory exists with expected contents
    assert!(project_dir.join(".claude/settings.json").exists());
    assert!(project_dir.join(".claude/agents/code-reviewer.md").exists());
    assert!(project_dir.join(".claude/skills/deploy-checklist/SKILL.md").exists());
    assert!(project_dir.join(".mcp.json").exists());

    // Verify agent has model injection
    let agent_content =
        fs::read_to_string(project_dir.join(".claude/agents/code-reviewer.md")).unwrap();
    assert!(agent_content.contains("model: opus"));
    assert!(agent_content.contains("AUTO-GENERATED BY agx"));

    // Verify skill has marker
    let skill_content =
        fs::read_to_string(project_dir.join(".claude/skills/deploy-checklist/SKILL.md")).unwrap();
    assert!(skill_content.contains("AUTO-GENERATED BY agx"));
    assert!(skill_content.contains("# Deploy Checklist"));

    // Gemini CLI backend
    let gemini_backend = get_backend("gemini-cli").unwrap();
    gemini_backend.generate(&resolved, project_dir).unwrap();

    // Verify .gemini/ directory exists with expected contents
    assert!(project_dir.join(".gemini/settings.json").exists());
    assert!(project_dir.join(".gemini/agents/code-reviewer.md").exists());
    assert!(project_dir.join(".gemini/skills/deploy-checklist/SKILL.md").exists());

    // 6. Generate context files
    generate_context_files(&manifest, project_dir).unwrap();

    // Verify CLAUDE.md has merged base + overlay
    let claude_md = fs::read_to_string(project_dir.join("CLAUDE.md")).unwrap();
    assert!(claude_md.contains("AUTO-GENERATED BY agx"));
    assert!(claude_md.contains("# Example Project"));
    assert!(claude_md.contains("# Claude-Specific Instructions"));

    // Verify GEMINI.md has base only (no gemini overlay in fixture)
    let gemini_md = fs::read_to_string(project_dir.join("GEMINI.md")).unwrap();
    assert!(gemini_md.contains("# Example Project"));
    assert!(!gemini_md.contains("# Claude-Specific Instructions"));

    // Verify AGENTS.md (generic fallback) is also generated
    let agents_md = fs::read_to_string(project_dir.join("AGENTS.md")).unwrap();
    assert!(agents_md.contains("# Example Project"));
}

// ---------------------------------------------------------------------------
// Test 2: Lockfile round-trip
// ---------------------------------------------------------------------------

#[test]
fn test_lockfile_roundtrip() {
    let tmp = tempdir().unwrap();
    let project_dir = tmp.path();
    setup_project(project_dir);

    // Load manifest and resolve
    let manifest_path = project_dir.join("agent-environment.yml");
    let manifest = manifest::load(&manifest_path).unwrap();
    let context = empty_resolve_context();
    let plugin_assets = BTreeMap::new();
    let lockfile = resolve_all(&manifest, &context, &plugin_assets).unwrap();

    // Save lockfile
    let lockfile_path = project_dir.join("agent-environment.lock");
    lockfile::save(&lockfile, &lockfile_path).unwrap();

    // Verify file was written
    assert!(lockfile_path.exists());
    let raw = fs::read_to_string(&lockfile_path).unwrap();
    assert!(raw.contains("AUTO-GENERATED BY agx"));

    // Load lockfile back
    let reloaded = lockfile::load(&lockfile_path).unwrap();

    // Verify contents match
    assert_eq!(reloaded.lockfile_version, lockfile.lockfile_version);
    assert_eq!(reloaded.skills.len(), lockfile.skills.len());
    assert_eq!(reloaded.agents.len(), lockfile.agents.len());
    assert_eq!(reloaded.plugins.len(), lockfile.plugins.len());

    // Verify specific entries survived the round-trip
    for key in lockfile.skills.keys() {
        assert!(
            reloaded.skills.contains_key(key),
            "missing skill: {key}"
        );
    }
    for key in lockfile.agents.keys() {
        assert!(
            reloaded.agents.contains_key(key),
            "missing agent: {key}"
        );
    }
}

// ---------------------------------------------------------------------------
// Test 3: Lockfile staleness detection
// ---------------------------------------------------------------------------

#[test]
fn test_lockfile_staleness() {
    let tmp = tempdir().unwrap();
    let project_dir = tmp.path();
    setup_project(project_dir);

    // Load manifest with skill A (deploy-checklist)
    let manifest_path = project_dir.join("agent-environment.yml");
    let manifest_v1 = manifest::load(&manifest_path).unwrap();

    // Resolve and produce lockfile
    let context = empty_resolve_context();
    let plugin_assets = BTreeMap::new();
    let lockfile = resolve_all(&manifest_v1, &context, &plugin_assets).unwrap();

    // Lockfile should NOT be stale for the original manifest
    assert!(
        !lockfile::is_stale(&lockfile, &manifest_v1),
        "lockfile should not be stale for original manifest"
    );

    // Modify manifest to add a second skill (skill B)
    let manifest_v2_yaml = r#"
name: example-project
backends:
  claude-code:
    isolation: strict
    model: sonnet
  gemini-cli:
    model: gemini-2.5-pro
skills:
  deploy-checklist:
    path: ./skills/deploy-checklist
  new-skill:
    path: ./skills/new-skill
agents:
  code-reviewer:
    path: ./agents/code-reviewer.md
    model: opus
context:
  base: ./CONTEXT.md
  overlays:
    claude-code: ./CONTEXT.claude.md
"#;
    fs::write(&manifest_path, manifest_v2_yaml).unwrap();
    let manifest_v2 = manifest::load(&manifest_path).unwrap();

    // Lockfile should now be stale (new-skill is missing)
    assert!(
        lockfile::is_stale(&lockfile, &manifest_v2),
        "lockfile should be stale after adding new skill"
    );
}

// ---------------------------------------------------------------------------
// Test 4: Manifest validation catches errors
// ---------------------------------------------------------------------------

#[test]
fn test_manifest_validation_catches_errors() {
    let fixture_path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/invalid-no-backends.yml");

    let manifest = manifest::load(&fixture_path).unwrap();
    let result = validate::validate(&manifest);

    assert!(result.is_err(), "validation should fail for no-backends manifest");
    let errors = result.unwrap_err();
    assert!(
        errors
            .iter()
            .any(|e| matches!(e, validate::ValidationError::NoBackends)),
        "should contain NoBackends error"
    );
}

// ---------------------------------------------------------------------------
// Test 5: Multi-backend generation
// ---------------------------------------------------------------------------

#[test]
fn test_multi_backend_generation() {
    let tmp = tempdir().unwrap();
    let project_dir = tmp.path();

    // Create a manifest with all three backends
    let manifest_yaml = r#"
name: multi-backend-project
backends:
  claude-code:
    isolation: strict
    model: sonnet
  gemini-cli:
    model: gemini-2.5-pro
  generic: {}
skills:
  deploy:
    path: ./skills/deploy
agents:
  reviewer:
    path: ./agents/reviewer.md
    model: opus
context:
  base: ./CONTEXT.md
"#;
    fs::write(project_dir.join("agent-environment.yml"), manifest_yaml).unwrap();

    // Create supporting files
    let skill_dir = project_dir.join("skills/deploy");
    fs::create_dir_all(&skill_dir).unwrap();
    fs::write(skill_dir.join("SKILL.md"), "# Deploy Skill\n").unwrap();

    let agents_dir = project_dir.join("agents");
    fs::create_dir_all(&agents_dir).unwrap();
    fs::write(agents_dir.join("reviewer.md"), "Review the code.\n").unwrap();

    fs::write(project_dir.join("CONTEXT.md"), "# Project Context\n").unwrap();

    // Load and resolve
    let manifest = manifest::load(&project_dir.join("agent-environment.yml")).unwrap();
    validate::validate(&manifest).unwrap();

    let context = empty_resolve_context();
    let plugin_assets = BTreeMap::new();
    let lockfile = resolve_all(&manifest, &context, &plugin_assets).unwrap();

    let cache_dir = tempdir().unwrap();
    let resolved = ResolvedEnvironment {
        manifest: &manifest,
        lockfile: &lockfile,
        cache_dir: cache_dir.path(),
    };

    // Generate for all three backends
    for backend_name in ["claude-code", "gemini-cli", "generic"] {
        let backend = get_backend(backend_name).unwrap();
        backend
            .generate(&resolved, project_dir)
            .unwrap_or_else(|e| panic!("generate failed for {backend_name}: {e}"));
    }

    // Claude Code outputs
    assert!(
        project_dir.join(".claude/settings.json").exists(),
        ".claude/settings.json should exist"
    );
    assert!(
        project_dir.join(".claude/agents/reviewer.md").exists(),
        ".claude/agents/reviewer.md should exist"
    );
    assert!(
        project_dir.join(".claude/skills/deploy/SKILL.md").exists(),
        ".claude/skills/deploy/SKILL.md should exist"
    );
    assert!(
        project_dir.join(".mcp.json").exists(),
        ".mcp.json should exist"
    );

    let claude_settings =
        fs::read_to_string(project_dir.join(".claude/settings.json")).unwrap();
    assert!(claude_settings.contains("DO NOT EDIT"));

    // Gemini CLI outputs
    assert!(
        project_dir.join(".gemini/settings.json").exists(),
        ".gemini/settings.json should exist"
    );
    assert!(
        project_dir.join(".gemini/agents/reviewer.md").exists(),
        ".gemini/agents/reviewer.md should exist"
    );
    assert!(
        project_dir.join(".gemini/skills/deploy/SKILL.md").exists(),
        ".gemini/skills/deploy/SKILL.md should exist"
    );

    let gemini_settings =
        fs::read_to_string(project_dir.join(".gemini/settings.json")).unwrap();
    assert!(gemini_settings.contains("DO NOT EDIT"));

    // Generic outputs
    assert!(
        project_dir.join("AGENTS.md").exists(),
        "AGENTS.md should exist"
    );
    assert!(
        project_dir.join(".agents/skills/deploy/SKILL.md").exists(),
        ".agents/skills/deploy/SKILL.md should exist"
    );

    let agents_md = fs::read_to_string(project_dir.join("AGENTS.md")).unwrap();
    assert!(agents_md.contains("DO NOT EDIT"));
    assert!(agents_md.contains("# Project Context"));

    // Generate context files and verify
    generate_context_files(&manifest, project_dir).unwrap();

    // With "generic" in backends, context::generate_context_files writes AGENTS.md
    // via the backend's context_filename(), and skips the extra AGENTS.md write.
    assert!(project_dir.join("CLAUDE.md").exists(), "CLAUDE.md should exist");
    assert!(project_dir.join("GEMINI.md").exists(), "GEMINI.md should exist");
    // AGENTS.md is written by context::generate_context_files for the generic backend
    assert!(project_dir.join("AGENTS.md").exists(), "AGENTS.md should exist");
}
