//! Lockfile reading, writing, and staleness detection for `agent-environment.lock`.

pub mod types;

use crate::manifest::types::AgentEnvironment;
use anyhow::{Context, Result};
use std::path::Path;
use types::Lockfile;

/// Read and parse a lockfile from a file path.
pub fn load(path: &Path) -> Result<Lockfile> {
    let content =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let lockfile: Lockfile =
        serde_yaml::from_str(&content).with_context(|| format!("parsing {}", path.display()))?;
    Ok(lockfile)
}

/// Serialize a lockfile and write it to a file path.
pub fn save(lockfile: &Lockfile, path: &Path) -> Result<()> {
    let header = "# agent-environment.lock\n# AUTO-GENERATED BY agx. DO NOT EDIT.\n";
    let content = serde_yaml::to_string(lockfile).context("serializing lockfile")?;
    std::fs::write(path, format!("{header}{content}"))
        .with_context(|| format!("writing {}", path.display()))?;
    Ok(())
}

/// Check whether the lockfile is stale relative to the manifest.
///
/// Returns `true` if the manifest contains plugin, skill, or agent entries
/// that are not present in the lockfile. This indicates that `agx lock` or
/// `agx install` needs to run to bring the lockfile up to date.
///
/// Note: this only checks for *missing* entries. It does not detect whether
/// version constraints have changed for existing entries — that requires a
/// full re-resolve.
pub fn is_stale(lockfile: &Lockfile, manifest: &AgentEnvironment) -> bool {
    // Check for manifest plugins not in lockfile
    for name in manifest.plugins.keys() {
        if !lockfile.plugins.contains_key(name) {
            return true;
        }
    }

    // Check for manifest skills not in lockfile
    for (name, skill) in &manifest.skills {
        // Local skills are always read from disk, so they don't need lockfile entries.
        // But if they're in the manifest and not in the lockfile, it's still stale
        // because the lockfile should track them (even with just a local source).
        if !lockfile.skills.contains_key(name) {
            // Git-sourced skills must be in the lockfile
            if skill.git.is_some() {
                return true;
            }
            // For local skills, we also track them for completeness
            if !lockfile.skills.contains_key(name) {
                return true;
            }
        }
    }

    // Check for manifest agents not in lockfile
    for (name, agent) in &manifest.agents {
        if !lockfile.agents.contains_key(name) {
            if agent.git.is_some() {
                return true;
            }
            if !lockfile.agents.contains_key(name) {
                return true;
            }
        }
    }

    // Check for lockfile entries that are no longer in the manifest (orphans)
    for name in lockfile.plugins.keys() {
        if !manifest.plugins.contains_key(name) {
            return true;
        }
    }
    for name in lockfile.skills.keys() {
        if !manifest.skills.contains_key(name) {
            return true;
        }
    }
    for name in lockfile.agents.keys() {
        if !manifest.agents.contains_key(name) {
            return true;
        }
    }

    false
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lockfile::types::{LockedAgent, LockedPlugin, LockedSkill, LockedSource};

    fn empty_manifest() -> AgentEnvironment {
        serde_yaml::from_str("name: test\nbackends:\n  claude-code: {}\n").unwrap()
    }

    fn empty_lockfile() -> Lockfile {
        Lockfile::new()
    }

    #[test]
    fn empty_manifest_and_lockfile_not_stale() {
        assert!(!is_stale(&empty_lockfile(), &empty_manifest()));
    }

    #[test]
    fn manifest_with_plugin_not_in_lockfile_is_stale() {
        let manifest: AgentEnvironment = serde_yaml::from_str(
            "name: test\nbackends:\n  claude-code: {}\nregistries:\n  r:\n    url: https://x.com\nplugins:\n  foo:\n    registry: r\n    version: '1.0.0'\n",
        ).unwrap();
        assert!(is_stale(&empty_lockfile(), &manifest));
    }

    #[test]
    fn manifest_with_skill_not_in_lockfile_is_stale() {
        let manifest: AgentEnvironment = serde_yaml::from_str(
            "name: test\nbackends:\n  claude-code: {}\nskills:\n  foo:\n    path: ./skills/foo\n",
        )
        .unwrap();
        assert!(is_stale(&empty_lockfile(), &manifest));
    }

    #[test]
    fn manifest_with_agent_not_in_lockfile_is_stale() {
        let manifest: AgentEnvironment = serde_yaml::from_str(
            "name: test\nbackends:\n  claude-code: {}\nagents:\n  foo:\n    path: ./agents/foo.md\n",
        )
        .unwrap();
        assert!(is_stale(&empty_lockfile(), &manifest));
    }

    #[test]
    fn lockfile_matching_manifest_not_stale() {
        let manifest: AgentEnvironment = serde_yaml::from_str(
            "name: test\nbackends:\n  claude-code: {}\nregistries:\n  r:\n    url: https://x.com\nplugins:\n  foo:\n    registry: r\n    version: '1.0.0'\nskills:\n  bar:\n    path: ./skills/bar\nagents:\n  baz:\n    path: ./agents/baz.md\n",
        ).unwrap();

        let mut lockfile = empty_lockfile();
        lockfile.plugins.insert(
            "foo".to_string(),
            LockedPlugin {
                source: LockedSource::Registry {
                    registry: "r".to_string(),
                    resolved_version: "1.0.0".to_string(),
                },
                git_commit: None,
                integrity: None,
            },
        );
        lockfile.skills.insert(
            "bar".to_string(),
            LockedSkill {
                source: LockedSource::Local {
                    local: "./skills/bar".to_string(),
                },
                git_commit: None,
                integrity: None,
            },
        );
        lockfile.agents.insert(
            "baz".to_string(),
            LockedAgent {
                source: LockedSource::Local {
                    local: "./agents/baz.md".to_string(),
                },
                git_commit: None,
                integrity: None,
            },
        );

        assert!(!is_stale(&lockfile, &manifest));
    }

    #[test]
    fn orphaned_lockfile_entry_is_stale() {
        let manifest = empty_manifest();
        let mut lockfile = empty_lockfile();
        lockfile.plugins.insert(
            "removed-plugin".to_string(),
            LockedPlugin {
                source: LockedSource::Registry {
                    registry: "r".to_string(),
                    resolved_version: "1.0.0".to_string(),
                },
                git_commit: None,
                integrity: None,
            },
        );
        assert!(is_stale(&lockfile, &manifest));
    }
}
