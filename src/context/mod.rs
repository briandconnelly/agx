//! Context file merging — combines CONTEXT.md base + overlays into backend-specific files.

use anyhow::{Context, Result};
use std::path::Path;

use crate::backends::get_backend;
use crate::manifest::types::AgentEnvironment;

/// Marker comment added to the top of generated context files.
const GENERATED_HEADER: &str = "<!-- AUTO-GENERATED BY agx from {sources}. DO NOT EDIT. -->\n\
<!-- To modify, edit the source files and run: agx generate -->\n\n";

/// Merge a base context file with an optional overlay, returning the combined content.
pub fn merge(base_path: &Path, overlay_path: Option<&Path>) -> Result<String> {
    let base = std::fs::read_to_string(base_path)
        .with_context(|| format!("reading base context {}", base_path.display()))?;

    let sources = if let Some(overlay) = overlay_path {
        let overlay_content = std::fs::read_to_string(overlay)
            .with_context(|| format!("reading overlay context {}", overlay.display()))?;

        let sources_str = format!(
            "{} + {}",
            base_path.file_name().unwrap().to_string_lossy(),
            overlay.file_name().unwrap().to_string_lossy()
        );
        let header = GENERATED_HEADER.replace("{sources}", &sources_str);

        format!("{header}{base}\n\n{overlay_content}\n")
    } else {
        let sources_str = base_path.file_name().unwrap().to_string_lossy().to_string();
        let header = GENERATED_HEADER.replace("{sources}", &sources_str);
        format!("{header}{base}\n")
    };

    Ok(sources)
}

/// Generate context files for all backends declared in the manifest.
///
/// For each backend, merges the base context file with the backend's overlay
/// (if any) and writes it to the backend's expected filename (CLAUDE.md,
/// GEMINI.md, AGENTS.md, etc.) at the project root.
///
/// If the `context` section is omitted from the manifest, this is a no-op.
pub fn generate_context_files(manifest: &AgentEnvironment, project_root: &Path) -> Result<()> {
    let context_config = match &manifest.context {
        Some(ctx) => ctx,
        None => return Ok(()), // No context section — skip entirely
    };

    let base_path = project_root.join(&context_config.base);

    // Generate context file for each declared backend
    for backend_name in manifest.backends.keys() {
        let backend = match get_backend(backend_name) {
            Some(b) => b,
            None => continue, // Unknown backend — skip
        };

        let overlay_path = context_config
            .overlays
            .get(backend_name.as_str())
            .map(|p| project_root.join(p));

        let merged = merge(&base_path, overlay_path.as_deref())
            .with_context(|| format!("merging context for backend '{backend_name}'"))?;

        let output_path = project_root.join(backend.context_filename());
        std::fs::write(&output_path, &merged)
            .with_context(|| format!("writing {}", output_path.display()))?;
    }

    // Generate AGENTS.md (generic/backend-agnostic) from base only,
    // but only if there isn't already a "generic" backend declared
    // (which would have been handled above).
    if !manifest.backends.contains_key("generic") {
        let merged = merge(&base_path, None)
            .context("merging context for AGENTS.md")?;
        let output_path = project_root.join("AGENTS.md");
        std::fs::write(&output_path, &merged)
            .with_context(|| format!("writing {}", output_path.display()))?;
    }

    // Handle child context files (monorepo support)
    for child in &context_config.children {
        let child_base_path = project_root.join(&child.base);
        let child_output_dir = project_root.join(&child.path);

        // Ensure the child directory exists
        std::fs::create_dir_all(&child_output_dir)
            .with_context(|| format!("creating child directory {}", child_output_dir.display()))?;

        for backend_name in manifest.backends.keys() {
            let backend = match get_backend(backend_name) {
                Some(b) => b,
                None => continue,
            };

            let overlay_path = child
                .overlays
                .get(backend_name.as_str())
                .map(|p| project_root.join(p));

            let merged = merge(&child_base_path, overlay_path.as_deref()).with_context(|| {
                format!(
                    "merging child context at {} for backend '{backend_name}'",
                    child.path
                )
            })?;

            let output_path = child_output_dir.join(backend.context_filename());
            std::fs::write(&output_path, &merged)
                .with_context(|| format!("writing {}", output_path.display()))?;
        }

        // AGENTS.md for child too (if no generic backend)
        if !manifest.backends.contains_key("generic") {
            let merged = merge(&child_base_path, None)
                .with_context(|| format!("merging child context at {} for AGENTS.md", child.path))?;
            let output_path = child_output_dir.join("AGENTS.md");
            std::fs::write(&output_path, &merged)
                .with_context(|| format!("writing {}", output_path.display()))?;
        }
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest::types::AgentEnvironment;
    use std::fs;
    use tempfile::tempdir;

    #[test]
    fn merge_base_only() {
        let dir = tempdir().unwrap();
        let base = dir.path().join("CONTEXT.md");
        fs::write(&base, "# Project\nThis is my project.").unwrap();

        let result = merge(&base, None).unwrap();
        assert!(result.starts_with("<!-- AUTO-GENERATED BY agx from CONTEXT.md. DO NOT EDIT. -->"));
        assert!(result.contains("# Project\nThis is my project."));
        assert!(!result.contains(" + "));
    }

    #[test]
    fn merge_base_with_overlay() {
        let dir = tempdir().unwrap();
        let base = dir.path().join("CONTEXT.md");
        let overlay = dir.path().join("CONTEXT.claude-code.md");

        fs::write(&base, "# Base content").unwrap();
        fs::write(&overlay, "# Claude-specific tips").unwrap();

        let result = merge(&base, Some(&overlay)).unwrap();
        assert!(result.contains("CONTEXT.md + CONTEXT.claude-code.md"));
        assert!(result.contains("# Base content"));
        assert!(result.contains("# Claude-specific tips"));
    }

    #[test]
    fn marker_comments_correct_format() {
        let dir = tempdir().unwrap();
        let base = dir.path().join("CONTEXT.md");
        fs::write(&base, "content").unwrap();

        let result = merge(&base, None).unwrap();
        assert!(result.contains("<!-- AUTO-GENERATED BY agx from CONTEXT.md. DO NOT EDIT. -->"));
        assert!(result.contains("<!-- To modify, edit the source files and run: agx generate -->"));
    }

    #[test]
    fn marker_comments_with_overlay() {
        let dir = tempdir().unwrap();
        let base = dir.path().join("CONTEXT.md");
        let overlay = dir.path().join("CONTEXT.gemini-cli.md");
        fs::write(&base, "base").unwrap();
        fs::write(&overlay, "overlay").unwrap();

        let result = merge(&base, Some(&overlay)).unwrap();
        assert!(result.contains("from CONTEXT.md + CONTEXT.gemini-cli.md."));
    }

    #[test]
    fn generate_context_files_skipped_when_section_omitted() {
        let manifest: AgentEnvironment = serde_yaml::from_str(
            "name: test\nbackends:\n  claude-code: {}\n",
        )
        .unwrap();
        let dir = tempdir().unwrap();

        // Should not create any files
        generate_context_files(&manifest, dir.path()).unwrap();
        assert!(!dir.path().join("CLAUDE.md").exists());
        assert!(!dir.path().join("AGENTS.md").exists());
    }

    #[test]
    fn generate_context_files_for_claude_code() {
        let dir = tempdir().unwrap();

        // Create source context files
        fs::write(dir.path().join("CONTEXT.md"), "# Project base").unwrap();
        fs::write(
            dir.path().join("CONTEXT.claude-code.md"),
            "# Claude-specific",
        )
        .unwrap();

        let manifest: AgentEnvironment = serde_yaml::from_str(&format!(
            r#"
name: test
backends:
  claude-code: {{}}
context:
  base: ./CONTEXT.md
  overlays:
    claude-code: ./CONTEXT.claude-code.md
"#
        ))
        .unwrap();

        generate_context_files(&manifest, dir.path()).unwrap();

        // CLAUDE.md should exist with merged content
        let claude_md = fs::read_to_string(dir.path().join("CLAUDE.md")).unwrap();
        assert!(claude_md.contains("# Project base"));
        assert!(claude_md.contains("# Claude-specific"));
        assert!(claude_md.contains("AUTO-GENERATED BY agx"));

        // AGENTS.md should exist with base only
        let agents_md = fs::read_to_string(dir.path().join("AGENTS.md")).unwrap();
        assert!(agents_md.contains("# Project base"));
        assert!(!agents_md.contains("# Claude-specific"));
    }

    #[test]
    fn generate_context_files_no_overlay_uses_base_only() {
        let dir = tempdir().unwrap();
        fs::write(dir.path().join("CONTEXT.md"), "# Base only").unwrap();

        let manifest: AgentEnvironment = serde_yaml::from_str(
            r#"
name: test
backends:
  claude-code: {}
context:
  base: ./CONTEXT.md
"#,
        )
        .unwrap();

        generate_context_files(&manifest, dir.path()).unwrap();

        let claude_md = fs::read_to_string(dir.path().join("CLAUDE.md")).unwrap();
        assert!(claude_md.contains("# Base only"));
        assert!(claude_md.contains("from CONTEXT.md."));
    }

    #[test]
    fn generate_context_files_with_children() {
        let dir = tempdir().unwrap();

        // Create root context
        fs::write(dir.path().join("CONTEXT.md"), "# Root base").unwrap();

        // Create child context
        let child_dir = dir.path().join("packages").join("api");
        fs::create_dir_all(&child_dir).unwrap();
        fs::write(child_dir.join("CONTEXT.md"), "# API base").unwrap();
        fs::write(
            child_dir.join("CONTEXT.claude-code.md"),
            "# API claude tips",
        )
        .unwrap();

        let manifest: AgentEnvironment = serde_yaml::from_str(
            r#"
name: test
backends:
  claude-code: {}
context:
  base: ./CONTEXT.md
  children:
    - path: ./packages/api
      base: ./packages/api/CONTEXT.md
      overlays:
        claude-code: ./packages/api/CONTEXT.claude-code.md
"#,
        )
        .unwrap();

        generate_context_files(&manifest, dir.path()).unwrap();

        // Root CLAUDE.md
        assert!(dir.path().join("CLAUDE.md").exists());

        // Child CLAUDE.md
        let child_claude = fs::read_to_string(child_dir.join("CLAUDE.md")).unwrap();
        assert!(child_claude.contains("# API base"));
        assert!(child_claude.contains("# API claude tips"));

        // Child AGENTS.md (base only)
        let child_agents = fs::read_to_string(child_dir.join("AGENTS.md")).unwrap();
        assert!(child_agents.contains("# API base"));
        assert!(!child_agents.contains("# API claude tips"));
    }

    #[test]
    fn generate_context_multiple_backends() {
        let dir = tempdir().unwrap();

        fs::write(dir.path().join("CONTEXT.md"), "# Project").unwrap();
        fs::write(
            dir.path().join("CONTEXT.claude-code.md"),
            "# Claude tips",
        )
        .unwrap();
        fs::write(
            dir.path().join("CONTEXT.gemini-cli.md"),
            "# Gemini tips",
        )
        .unwrap();

        let manifest: AgentEnvironment = serde_yaml::from_str(
            r#"
name: test
backends:
  claude-code: {}
  gemini-cli: {}
context:
  base: ./CONTEXT.md
  overlays:
    claude-code: ./CONTEXT.claude-code.md
    gemini-cli: ./CONTEXT.gemini-cli.md
"#,
        )
        .unwrap();

        generate_context_files(&manifest, dir.path()).unwrap();

        let claude_md = fs::read_to_string(dir.path().join("CLAUDE.md")).unwrap();
        assert!(claude_md.contains("# Claude tips"));
        assert!(!claude_md.contains("# Gemini tips"));

        let gemini_md = fs::read_to_string(dir.path().join("GEMINI.md")).unwrap();
        assert!(gemini_md.contains("# Gemini tips"));
        assert!(!gemini_md.contains("# Claude tips"));
    }
}
